    def _update_assets(
        self, assets0: T.Assets0, start_directory: T.StartDirectory
    ) -> T.Assets1:
        return index_assets(assets0, start_directory)

    def _update_dependencies(
        self, deps0: T.Dependencies0, start_directory: T.StartDirectory
    ) -> T.Dependencies1:
        if not deps0:  # None, empty dict, empty str.
            return {}
        elif isinstance(deps0, str):
            if deps0 == 'uv':
                return resolve_dependencies('uv.lock', start_directory)
            else:  # 'poetry'
                return resolve_dependencies('poetry.lock', start_directory)
        else:  # dict
            minify_dependencies(
                start_directory,
                deps0['options']['entries'],
                deps0['options']['search_paths'],
                deps0['options']['export'],
                deps0['base'],
            )
            return {}

    def _update_encryption(
        self,
        options: T.Encryption0,
        appid: str,
        start_directory: T.StartDirectory,
    ) -> T.Encryption1:
        assert options

        from ..cache import get_project_cache
        from ..cache import is_project_cached
        from ..cache import save_project_cache

        def determine_encryption_key() -> str:
            key0 = options['key']
            if key0 == '$env':
                key1 = os.environ['DEPSLAND_APP_SECRET_KEY']
            elif key0.startswith('$env:'):
                key1 = os.environ[key0[5:]]
            else:
                key1 = key0
            if options.get('add_salt'):
                key1 = pyportable_crypto.keygen.add_salt(key1)
            if key1 != key0:
                print(
                    'resolved encryption key: {} -> {}'.format(key0, key1),
                    ':r2',
                )
            return key1

        def check_if_reusable() -> bool:
            if not fs.exist(
                _abspath('{}/pyportable_runtime'.format(options['output']))
            ):
                return False
            if not is_project_cached(appid):
                return False
            proj_cache = get_project_cache(appid, options, start_directory)
            enc_cache = proj_cache['encryption']
            assert enc_cache
            if enc_cache['key_hash'] != hash_text(options['key']):
                return False
            if enc_cache['output'] != options['output']:
                return False
            for k0, v0 in enc_cache['packages'].items():
                if k0 not in options['packages']:
                    return False
                if v0 != fs.mtime(
                    '{}/{}'.format(start_directory, k0), recursive=True
                ):
                    return False
            return True

        def encrypt_source() -> None:
            fs.copy_tree(
                pyportable_crypto.generate_cipher_package(options['key']),
                _abspath('{}/pyportable_runtime'.format(options['output'])),
                True,
            )
            for pkg_relpath in options['packages']:
                pyportable_crypto.compile_package(
                    dir_i=_abspath(pkg_relpath),
                    dir_o=_abspath(
                        '{}/{}'.format(
                            options['output'], fs.barename(pkg_relpath)
                        )
                    ),
                    key=options['key'],
                    add_runtime_package='none',
                )

        def save_changes() -> None:
            save_project_cache(appid, options, start_directory)

        def _abspath(relpath: T.RelPath) -> T.AbsPath:
            return '{}/{}'.format(start_directory, relpath)

        options['key'] = determine_encryption_key()
        if check_if_reusable():
            print('reuse encrypted resources from last time', ':v3')
        else:
            encrypt_source()
            save_changes()
        return options

    def _update_launcher(
        self, launcher0: T.Launcher0, start_directory: T.StartDirectory
    ) -> T.Launcher1:
        out: T.Launcher1 = {
            'command': '',
            'icon': '',
            'show_console': True,
            'enable_cli': False,
            'add_to_desktop': False,
            'add_to_start_menu': False,
        }

        if isinstance(launcher0['command'], str):
            out['command'] = launcher0['command']
        else:
            out['command'] = shlex.join(launcher0['command'])

        if launcher0.get('icon'):
            out['icon'] = self._make_relpath(launcher0['icon'], start_directory)
            # print(out['icon'], ':v')

        for k in (
            'show_console',
            'enable_cli',
            'add_to_desktop',
            'add_to_start_menu',
        ):
            if k in launcher0:
                assert isinstance((v := launcher0[k]), bool)
                out[k] = v

        return out

    def _update_readme_file(
        self, readme: tp.Optional[T.Readme0], start_directory: T.StartDirectory
    ) -> T.Readme1:
        out: T.Readme1 = {
            'file': '',
            'name': '',
            'icon': '',
            'standalone': True,
        }
        if readme:
            if isinstance(readme, str):
                out['file'] = self._make_relpath(readme, start_directory)
                out['name'] = fs.barename(out['file'])
            else:
                if readme['file']:
                    out['file'] = self._make_relpath(
                        readme['file'], start_directory
                    )
                    out['name'] = readme.get('name', fs.barename(out['file']))
                    out['standalone'] = readme.get('standalone', True)
                    if readme.get('icon'):
                        out['icon'] = self._make_relpath(
                            readme['icon'], start_directory
                        )
        return out

    def _update_version(
        self, version: str, start_directory: T.StartDirectory
    ) -> str:
        if version == '$pyproject_version':
            return fs.load('{}/pyproject.toml'.format(start_directory))[
                'project'
            ]['version']
        return version

    # --------------------------------------------------------------------------

    @staticmethod
    def _make_relpath(path: T.AnyPath, base: T.AbsPath) -> T.RelPath:
        if os.path.isabs(path):
            assert fs.normpath(path).startswith(base + '/')
            return fs.relpath(path, base)
        else:
            return fs.normpath(path)

    @staticmethod
    def _plainify_assets(assets1: T.Assets1) -> T.Assets0:
        out = []
        for path, info in assets1.items():
            if info.scheme is not None:
                path += ':{:02b}'.format(info.scheme)
            out.append(path)
        return out


