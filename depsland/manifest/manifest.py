    @staticmethod
    def _pre_process_manifest(
        manifest: T.Manifest0, start_directory: T.StartDirectory
    ) -> None:
        # assert required keys
        required_keys = ('appid', 'name', 'version', 'assets', 'launcher')
        assert all(x in manifest for x in required_keys), (
            'missing required keys',
            'required: {}'.format(required_keys),
            'found: {}'.format(tuple(manifest.keys())),
        )

        assert norm.check_name_normalized(manifest['appid']), (
            'the appid should be lowercase and only contain alphanumber and '
            'underscore.'
        )

        if manifest['version'][0] == '$':
            assert manifest['version'] == '$pyproject_version'
            assert fs.exist('{}/pyproject.toml'.format(start_directory)), (
                'when you configured version to "$pyproject_version", you '
                'should have a "pyproject.toml" file in your project root.'
            )
        else:
            assert re.fullmatch(
                r'\d+\.\d+\.\d+([ab]\d+)?', manifest['version']
            ), manifest['version']

        if manifest.get('readme'):
            assert manifest['readme']
            if isinstance(manifest['readme'], str):
                readme = manifest['readme']
            else:
                if name := manifest['readme'].get('name'):
                    if name.endswith(
                        (
                            '.doc',
                            '.docx',
                            '.htm',
                            '.html',
                            '.md',
                            '.mhtml',
                            '.mp4',
                            '.pdf',
                            '.rst',
                            '.txt',
                            '.wps',
                        )
                    ):
                        raise Exception(
                            'do not include extension in the `readme:name` '
                            'field',
                            manifest['readme']['name'],
                        )
                readme = manifest['readme']['file']
            if readme:
                assert '.' in fs.filename(readme), (
                    'there should be a file extension in your readme file name.'
                    # otherwise it maybe a directory or, we cannot make a proper
                    # name for it in installation stage.
                )

        assert manifest['assets'], 'field `assets` cannot be empty!'
        assert isinstance(manifest['assets'], list)
        assert all(not x.startswith('../') for x in manifest['assets']), (
            'manifest should be put at the root of project, and there shall be '
            'no "../" in your assets keys.'
        )

        if enc := manifest.get('encryption'):
            if not any(enc.values()):
                manifest['encryption'] = None
            else:
                assert enc['key'] and enc['packages'], enc
                assert all(x in manifest['assets'] for x in enc['packages'])
                assert all(
                    fs.exist('{}/{}'.format(start_directory, x))
                    for x in enc['packages']
                )
                if enc['output']:
                    if not fs.exist(
                        '{}/{}'.format(start_directory, enc['output'])
                    ):
                        fs.make_dir(
                            '{}/{}'.format(start_directory, enc['output'])
                        )
                else:
                    enc['output'] = '.depsland/encrypted_packages'
                    fs.make_dirs('{}/{}'.format(start_directory, enc['output']))

        if manifest.get('dependencies'):
            if isinstance(manifest['dependencies'], str):
                if manifest['dependencies'] in ('poetry.lock', 'uv.lock'):
                    print(
                        'remove ".lock" from dependency setting '
                        '({} -> {})'.format(
                            manifest['dependencies'],
                            manifest['dependencies'][:-5],
                        ),
                        ':v6',
                    )
                    manifest['dependencies'] = manifest['dependencies'][:-5]
                else:
                    assert manifest['dependencies'] in ('poetry', 'uv')
            else:  # dict
                assert isinstance(manifest['dependencies'], dict)
                deps_dict = manifest['dependencies']

                assert deps_dict['method'] == 'tree_shaking', deps_dict

                if 'base' in deps_dict:
                    assert deps_dict['base'] in ('poetry.lock', 'uv.lock')
                else:
                    deps_dict['base'] = 'uv.lock'

                assert 'options' in deps_dict
                options = deps_dict['options']

                assert 'root' not in options, (
                    '"root" field in tree-shaking options is managed by '
                    'depsland, do not set it manually.'
                )
                options['root'] = '..'

                if 'export' in options:
                    assert (
                        options['export']['source']
                        and options['export']['target']
                    )
                else:
                    options['export'] = {
                        'source': '.depsland/orig_deps',
                        'target': '.depsland/mini_deps',
                    }

                assert options['entries']

                if 'search_paths' in options:
                    if '.depsland/orig_deps' not in options['search_paths']:
                        options['search_paths'].insert(0, '.depsland/orig_deps')
                else:
                    options['search_paths'] = ['.depsland/orig_deps', '.']

        launcher: T.Launcher0 = manifest['launcher']
        assert launcher['command'], 'field `launcher.command` cannot be empty!'
        if '<python>' in launcher['command']:
            # print(':v6', '"<python>" is deprecate to use, use just "python"')
            # if isinstance(launcher['command'], str):
            #     launcher['command'] = \
            #         launcher['command'].replace('<python>', 'python')
            # else:
            #     assert launcher['command'][0] == '<python>'
            #     launcher['command'][0] = 'python'
            raise Exception(
                '"<python>" is deprecate to use, use just "python" in your '
                'launcher command.'
            )

    def _post_process_manifest(
        self, manifest: T.Manifest1, origin_dependency_setting: T.Dependencies0
    ) -> None:
        # inflate assets from tree_shaking cache
        if (
            origin_dependency_setting
            and isinstance(origin_dependency_setting, dict)
            and origin_dependency_setting['method'] == 'tree_shaking'
        ):
            mini_deps_cache_file = get_tree_shaking_cache_file(
                manifest['start_directory'], origin_dependency_setting['base']
            )
            print('inflate assets from ".depsland/mini_deps/*"')
            manifest['assets'].update(fs.load(mini_deps_cache_file))

        # update assets redirection
        if enc := manifest['encryption']:
            print(
                'redirect part of assets to encrypted ones',
                enc['packages'],
                ':ln',
            )
            manifest['assets_redirection'].update(
                {
                    k: '{}/{}'.format(enc['output'], fs.barename(k))
                    for k in enc['packages']
                }
            )
            manifest['assets'].update(
                self._update_assets(
                    ['{}/pyportable_runtime'.format(enc['output'])],
                    manifest['start_directory'],
                )
            )

        if x := manifest['launcher']['icon']:
            assert x.endswith('.ico'), (
                'make sure the icon file is ".ico" format. if you have other '
                'file type, please use a online converter (for example '
                'https://findicons.com/convert) to get one.'
            )
            # TODO: check icon size and give suggestions (the size is -
            #   suggested 128x128 or higher.)
        if manifest['launcher']['add_to_start_menu']:
            print(
                ':v6',
                '`launcher:add_to_start_menu` is not tested yet. this is an '
                'experimental feature.',
            )

