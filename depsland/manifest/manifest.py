class Manifest:
    """
    doc: @wiki/src/developer/manifest-path-format.md
    """

    _file: T.AbsPath
    _manifest: T.Manifest1

    @classmethod
    def init(cls, appid: str, appname: str) -> 'Manifest':
        from .. import __version__

        self = Manifest()
        self._file = ''
        self._manifest = {
            'appid': appid,
            'name': appname,
            'version': '0.0.0',
            'start_directory': '',
            'readme': {'file': '', 'name': '', 'icon': '', 'standalone': True},
            'assets': {},
            'assets_redirection': {},
            'encryption': None,
            'dependencies': {},
            'launcher': {
                'command': '',
                'icon': '',
                'show_console': True,
                'enable_cli': False,
                'add_to_desktop': True,
                'add_to_start_menu': False,
            },
            'experiments': {'package_provider': 'pypi'},
            'depsland_version': __version__,
        }
        return self

    @classmethod
    @cache
    def load_from_file(
        cls, file: T.AnyPath, start_directory: T.AnyPath = ''
    ) -> 'Manifest':
        """
        args:
            file: support '.json', '.yaml'/'.yml', '.pkl' formats.
                the pickle format was generated by depsland itself, and trusted
                by depsland. loading pickle file is faster (since it skips many
                check steps) and more stable (reproducible).
        """
        from .. import __version__

        self = Manifest()
        self._file = fs.abspath(file)
        cfg_dir = fs.parent(self._file)  # abspath

        data0: tp.Union[T.Manifest0, T.Manifest1]
        data1: T.Manifest1

        if self._file.endswith('.pkl'):
            data0: T.Manifest1 = fs.load(self._file)
            data1 = data0
            data1['start_directory'] = start_directory or cfg_dir
        else:
            data0: T.Manifest0
            if self._file.endswith(('.json', '.yaml')):
                data0 = fs.load(self._file)
            elif fs.basename(self._file) == 'pyproject.toml':
                data0 = fs.load(self._file)['tool']['depsland']['manifest']
            elif self._file.endswith('.toml'):
                try:
                    data0 = fs.load(self._file)['tool']['depsland']['manifest']
                except KeyError:
                    data0 = fs.load(self._file)
            else:
                raise Exception('unsupported manifest file format', self._file)

            if not start_directory:
                if 'start_directory' in data0:
                    x = data0['start_directory']
                    if x.startswith('.'):
                        start_directory = fs.normpath(
                            '{}/{}'.format(cfg_dir, x)
                        )
                    else:
                        start_directory = fs.abspath(x)
                else:
                    start_directory = cfg_dir
            print(start_directory, ':v2n')

            if data0.get('readme'):
                if isinstance((x := data0['readme']), str):
                    data0['assets'].append(x)
                elif x := data0['readme']['file']:
                    data0['assets'].append(x)
            if x := data0['launcher'].get('icon'):
                data0['assets'].append(x)
            if data0.get('dependencies'):
                # FIXME: not recommended
                def deduce_entry() -> T.RelPath:
                    if isinstance(data0['launcher']['command'], str):
                        x = shlex.split(data0['launcher']['command'])[1]
                    else:
                        x = data0['launcher']['command'][1]
                    assert x.endswith('.py')
                    return x

                if isinstance(data0['dependencies'], str):
                    if data0['dependencies'] == 'tree_shaking':
                        data0['dependencies'] = {
                            'method': 'tree_shaking',
                            'options': {'entries': [deduce_entry()]},
                        }
                elif data0['dependencies']['method'] == 'tree_shaking':
                    if 'options' in data0['dependencies']:
                        if 'entries' not in data0['dependencies']['options']:
                            data0['dependencies']['options']['entries'] = [
                                deduce_entry()
                            ]
                    else:
                        data0['dependencies']['options'] = {
                            'entries': [deduce_entry()]
                        }

            self._pre_process_manifest(data0, start_directory)
            data1 = {
                'appid': data0['appid'],
                'name': data0['name'],
                'version': self._update_version(
                    data0['version'], start_directory
                ),
                'start_directory': start_directory,
                'readme': self._update_readme_file(
                    data0.get('readme', None), start_directory
                ),
                'assets': self._update_assets(data0['assets'], start_directory),
                'assets_redirection': {},
                'encryption': (
                    self._update_encryption(
                        data0['encryption'], data0['appid'], start_directory
                    )
                    if data0.get('encryption')
                    else None
                ),
                'dependencies': self._update_dependencies(
                    data0.get('dependencies'), start_directory
                ),
                'launcher': self._update_launcher(
                    data0['launcher'], start_directory
                ),
                'experiments': data0.get(
                    'experiments', {'package_provider': 'pypi'}
                ),
                'depsland_version': data0.get('depsland_version', __version__),
            }
            self._post_process_manifest(
                data1, origin_dependency_setting=data0.get('dependencies')
            )

        self._manifest = data1
        return self

    def dump_to_file(self, file: T.AnyPath = '') -> None:
        if not file:
            file = self._file
        if fs.basename(file) == 'pyproject.toml':
            # TODO: how to reserve original comments?
            raise NotImplementedError(file)

        data1: T.Manifest1 = self._manifest
        data0: T.Manifest0 = self._manifest.copy()  # type: ignore

        # modify `data0` fields
        # be noticed some of `data0.values()` are list or dict types, which -
        # should be deep copied if we want to modify their inner items, to -
        # avoid affecting the original data of `data1`.
        data0.pop('start_directory')
        if not file.endswith('.pkl'):
            data0['assets'] = self._plainify_assets(data1['assets'])
            if file.endswith('.toml'):
                data0 = {
                    'tool': {'depsland': {'manifest': data0}}  # type: ignore
                }

        fs.dump(data0, file)

    def make_tree(self, root: str = '') -> None:
        if not root:
            root = self._manifest['start_directory']
        relpaths = []
        for k, v in self._manifest['assets'].items():
            if v.type == 'dir':
                relpaths.append(k)
            else:
                if '/' in k:
                    relpaths.append(k.rsplit('/', 1)[0])
        init_target_tree(root, relpaths)

    # --------------------------------------------------------------------------
    # dict-like behavior

    @property
    def model(self) -> T.Manifest1:
        return self._manifest

    def get(self, key: str) -> tp.Any:
        if key in self._manifest:
            return self[key]
        return None

    def __iter__(self) -> tp.Iterator[tp.Tuple[str, tp.Any]]:
        yield from self._manifest.items()

    def __getitem__(self, key: str) -> tp.Any:
        if key == 'readme':

            class ReadmeGetter:
                def __init__(
                    self, data: T.Readme1, start_directory: T.StartDirectory
                ) -> None:
                    self._data = data
                    self._start_directory = start_directory

                def __bool__(self) -> bool:
                    return bool(self._data['file'])

                def __iter__(self) -> tp.Iterator[tp.Tuple[str, tp.Any]]:
                    yield from self._data.items()

                def __getitem__(self, key: str) -> tp.Union[str, bool]:
                    if key == 'file' or key == 'icon':
                        if x := self._data[key]:  # type: ignore
                            return '{}/{}'.format(self._start_directory, x)
                        else:
                            return ''
                    else:
                        return self._data[key]  # type: ignore

                def __setitem__(self, key: str, value: tp.Any) -> None:
                    raise Exception('cannot modify readme dict', key, value)

            return ReadmeGetter(
                self._manifest['readme'], self._manifest['start_directory']
            )

        elif key == 'encryption':

            class EncryptionGetter:
                def __init__(
                    self, data: T.Encryption1, start_directory: T.StartDirectory
                ):
                    self._data = data
                    self._start_directory = start_directory

                def __getitem__(
                    self, key: tp.Literal['key', 'packages', 'output']
                ) -> tp.Any:
                    if key == 'output':
                        return '{}/{}'.format(
                            self._start_directory, self._data[key]
                        )
                    elif key == 'packages':
                        return tuple(
                            '{}/{}'.format(self._start_directory, x)
                            for x in self._data[key]
                        )
                    else:
                        return self._data[key]

            return (
                EncryptionGetter(
                    self._manifest['encryption'],
                    self._manifest['start_directory'],
                )
                if self._manifest['encryption']
                else None
            )

        elif key == 'launcher':

            class LauncherGetter:
                def __init__(
                    self, data: T.Launcher1, start_directory: T.StartDirectory
                ) -> None:
                    self._data = data
                    self._start_directory = start_directory

                def __iter__(self) -> tp.Iterator[tp.Tuple[str, tp.Any]]:
                    yield from self._data.items()

                def __getitem__(self, key: str) -> tp.Union[str, bool]:
                    if key == 'icon':
                        if x := self._data['icon']:
                            return '{}/{}'.format(self._start_directory, x)
                        else:
                            return ''
                    else:
                        return self._data[key]  # type: ignore

                def __setitem__(self, key: str, value: tp.Any) -> None:
                    raise Exception('cannot modify launcher dict', key, value)

            return LauncherGetter(
                self._manifest['launcher'], self._manifest['start_directory']
            )

        else:
            return self._manifest[key]  # type: ignore

    def __setitem__(self, key: str, value: tp.Any) -> None:
        if key == 'start_directory':
            assert os.path.isabs(value)
            self._manifest[key] = value  # type: ignore
        else:
            raise Exception('cannot modify top field of manifest!', key, value)

